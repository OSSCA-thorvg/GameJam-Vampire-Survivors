import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { format } from 'prettier';
import { parseCatalog, type CatalogRow } from '../packages/shared/src/catalog.js';

export async function renderAssetIds(rows: CatalogRow[]): Promise<string> {
  const sorted = [...rows].sort((a, b) => a.id.localeCompare(b.id, 'en'));
  return format(
    `// Generated by pnpm assets:sync from assets/CATALOG.md. Do not edit.\n` +
      `export const ASSET_IDS = ${JSON.stringify(sorted.map((row) => row.id))} as const;\n` +
      `export const ASSET_SIZES = ${JSON.stringify(Object.fromEntries(sorted.map((row) => [row.id, row.size])))} as const;\n`,
    { parser: 'typescript', singleQuote: true, trailingComma: 'all', printWidth: 100 },
  );
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const catalog = await readFile(new URL('../assets/CATALOG.md', import.meta.url), 'utf8');
  await writeFile(
    fileURLToPath(new URL('../packages/shared/src/generated/asset-ids.ts', import.meta.url)),
    await renderAssetIds(parseCatalog(catalog)),
  );
}
